#!/usr/bin/env python3
"""Generate the gap function registration include for the ps2x runtime.

Ghidra never turned parts of the game executable into functions, so the
recompiler skips those address ranges and the guest falls off the end of the
translated code when the game JALRs into one of them.  We recover them by
splitting the uncovered ranges into functions (derive_gap_map.py), running
ps2_recomp over the augmented map and dropping the results into
ps2xRuntime/src/lib/gap_functions/.

Those translated files are game-derived and stay out of the repository, so the
handful of lines that register them are generated here instead of being
committed.  game_overrides.cpp includes the result with __has_include, so a
tree without the generated files still builds (it just has fewer handlers).

Usage: gen_gap_registry.py [gap_dir]
"""

import glob
import os
import re
import sys

GAP_DIR = sys.argv[1] if len(sys.argv) > 1 else "PS2Recomp/ps2xRuntime/src/lib/gap_functions"
OUT = os.path.join(GAP_DIR, "gap_registry.inc")

entries = []
for path in glob.glob(os.path.join(GAP_DIR, "entry_gap_*.cpp")):
    text = open(path, encoding="utf-8", errors="replace").read()
    m = re.search(r"^void (entry_gap_\S+?)\(uint8_t\s*\*\s*rdram", text, re.M)
    if not m:
        continue
    name = m.group(1)
    a = re.search(r"entry_gap_([0-9a-f]{8})", name)
    if not a:
        continue
    entries.append((int(a.group(1), 16), name))

entries.sort()

lines = [
    "// Generated by tools/gen_gap_registry.py - do not edit.",
    "// Registers the translated Ghidra analysis gaps found in this tree.",
    "//",
    "// The declarations have to sit at global scope (this file is included at",
    "// file scope) so they refer to the global entry_gap_* symbols and not to",
    "// namespace members.",
]
for _, name in entries:
    lines.append(
        "extern void %s(uint8_t *, R5900Context *, PS2Runtime *);" % name
    )
lines.append("")
lines.append("namespace ps2_gap_registry")
lines.append("{")
lines.append("inline void registerHandlers(PS2Runtime &runtime)")
lines.append("{")
lines.append("    static const struct")
lines.append("    {")
lines.append("        uint32_t address;")
lines.append("        void (*function)(uint8_t *, R5900Context *, PS2Runtime *);")
lines.append("    } gapRegistry[] = {")
for addr, name in entries:
    lines.append("        {0x%08Xu, %s}," % (addr, name))
lines.append("    };")
lines.append("    for (const auto &gap : gapRegistry)")
lines.append("    {")
lines.append("        runtime.registerFunction(gap.address, gap.function);")
lines.append("    }")
lines.append("}")
lines.append("} // namespace ps2_gap_registry")

open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote %s with %d gap handlers" % (OUT, len(entries)))
