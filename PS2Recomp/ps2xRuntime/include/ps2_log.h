// RUNTIME_LOG variant for the noisy bring-up dumps: compiled in when logging
// is enabled, but additionally gated on PS2_TRACE at runtime. Boot messages
// keep using RUNTIME_LOG; per-event diagnostics use TRACE_LOG.
#if PS2_RUNTIME_LOGS || AGRESSIVE_LOGS
#define TRACE_LOG(x)                          \
    do                                        \
    {                                         \
        if (::ps2_log::debug_trace_enabled()) \
        {                                     \
            RUNTIME_LOG(x);                   \
        }                                     \
    } while (0)
#else
#define TRACE_LOG(x) do {} while (0)
#endif

