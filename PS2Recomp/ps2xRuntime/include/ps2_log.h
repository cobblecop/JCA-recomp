namespace ps2_log
{
inline std::string log_path()
{
    static std::string path;
    if (path.empty())
    {
        path = (std::filesystem::current_path() / "ps2_log.txt").string();
    }
    return path;
}
inline std::ostream &log_stream()
{
    static std::ofstream f(log_path(), std::ios::out);
    return f.is_open() ? f : std::cerr;
}
inline int &depth()
{
    static thread_local int d = 0;
    return d;
}
// Runtime gate: per-function tracing is extremely expensive (an fstream
// write + flush on every call), so it is now opt-in via PS2_FUNC_TRACE=1.
// Without the env var the tracker compiles in but records nothing.
inline bool trace_enabled()
{
    static const bool enabled = []() {
        const char *e = std::getenv("PS2_FUNC_TRACE");
        return e != nullptr && e[0] != '\0' && e[0] != '0';
    }();
    return enabled;
}
inline void log_entry(const char *name)
{
    if (!trace_enabled())
        return;
    for (int i = 0; i < depth(); ++i)
        log_stream() << '\t';
    log_stream() << ">> " << name << " enter\n";
    log_stream().flush();
    depth()++;
}
inline void log_exit(const char *name)
{
    if (!trace_enabled())
        return;
    depth()--;
    for (int i = 0; i < depth(); ++i)
        log_stream() << '\t';
    log_stream() << "<< " << name << " exit\n";
    log_stream().flush();
}
inline void print_saved_location()
{
    std::cout << "[PS2 LOG] Logs saved at " << log_path() << std::endl;
}
}

