// Runtime gate for the noisy per-frame bring-up diagnostics (work-queue
// submissions, GIF submits, scheduler watchdog, SIF DMA lists). They are off
// by default so a normal run stays quiet; PS2_TRACE=1 turns them back on.
namespace ps2_log
{
inline bool debug_trace_enabled()
{
    static const bool enabled = []() {
        const char *e = std::getenv("PS2_TRACE");
        return e != nullptr && e[0] != '\0' && e[0] != '0';
    }();
    return enabled;
}
}
// Variadic so the guarded block may contain commas.
#define PS2_IF_TRACE(...)                     \
    do                                        \
    {                                         \
        if (::ps2_log::debug_trace_enabled()) \
        {                                     \
            __VA_ARGS__;                      \
        }                                     \
    } while (0)

#define RUNTIME_ERROR(x)                                                                                               \
